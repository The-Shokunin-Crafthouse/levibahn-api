// Crawls the live levibahn.com and writes the visible text of every page to
// lib/site.generated.ts, which the system prompt carries after FACTS.
// Skips /2026 (the previous site), the ai.levibahn.com docroot (/ai), PR previews,
// and assets. Run: npm run build:site-facts. Commit the output; never hand-edit it.

import { writeFileSync } from 'node:fs';

const ORIGIN = 'https://levibahn.com';
const SKIP = [/^\/2026(\/|$)/, /^\/ai(\/|$)/, /^\/_/, /^\/api(\/|$)/, /^\/protected-assets/, /^\/404/, /^\/lab(\/|$)/, /^\/wayback(\/|$)/, /^\/2025\/$/];
const ASSET = /\.(png|jpe?g|gif|webp|avif|svg|ico|mp4|webm|pdf|zip|css|js|json|txt|xml|woff2?)$/i;
const MAX_PAGES = 80;

function normalize(href, from) {
  let url;
  try { url = new URL(href, from); } catch { return null; }
  if (url.origin !== ORIGIN) return null;
  let path = url.pathname.replace(/\/index\.html$/, '/');
  if (!path.endsWith('/') && !ASSET.test(path)) path += '/';
  if (ASSET.test(path) || SKIP.some((re) => re.test(path))) return null;
  return path;
}

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rsquo: '’', lsquo: '‘', rdquo: '”', ldquo: '“', mdash: '—', ndash: '–', hellip: '…' };
function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
}

function visibleText(html) {
  const body = (html.match(/<main[\s\S]*?<\/main>/i) ?? html.match(/<body[\s\S]*<\/body>/i) ?? [html])[0];
  return decode(
    body
      .replace(/<(script|style|noscript|svg|template|nav|footer)[\s\S]*?<\/\1>/gi, ' ')
      .replace(/<!--[\s\S]*?-->/g, ' ')
      .replace(/<(br|\/p|\/h[1-6]|\/li|\/div|\/section|\/article|\/figcaption|\/blockquote|\/tr)\b[^>]*>/gi, '\n')
      .replace(/<li\b[^>]*>/gi, '\n- ')
      .replace(/<[^>]+>/g, ' '),
  )
    .split('\n')
    .map((l) => l.replace(/\s+/g, ' ').trim())
    .filter((l, i, all) => l && l !== all[i - 1])
    .join('\n');
}

// /resume/ is live but no nav links to it. /lab/ (internal component lab) and /wayback/ are skipped.
const queue = ['/', '/resume/'];
const seen = new Set(queue);
const pages = [];
while (queue.length && pages.length < MAX_PAGES) {
  const path = queue.shift();
  const res = await fetch(ORIGIN + path, { redirect: 'follow' });
  const finalPath = normalize(res.url, ORIGIN);
  if (!res.ok || !(res.headers.get('content-type') ?? '').includes('text/html') || !finalPath) continue;
  if (pages.some((p) => p.path === finalPath)) continue;
  const html = await res.text();
  const title = decode((html.match(/<title>([\s\S]*?)<\/title>/i) ?? [, path])[1]).trim();
  if (/does not exist|not found/i.test(title)) continue;
  for (const m of html.matchAll(/href="([^"#?]+)/g)) {
    const next = normalize(m[1], ORIGIN + path);
    if (next && !seen.has(next)) { seen.add(next); queue.push(next); }
  }
  const text = visibleText(html);
  if (text.length > 80) pages.push({ path: finalPath, title, text });
}

pages.sort((a, b) => a.path.localeCompare(b.path));
const body = pages.map((p) => `PAGE ${ORIGIN}${p.path} (${p.title})\n${p.text}`).join('\n\n');
writeFileSync(
  new URL('../lib/site.generated.ts', import.meta.url),
  `// GENERATED by scripts/build-site-facts.mjs from the live ${ORIGIN} (excluding /2026). Do not edit.\n` +
    `// Pages: ${pages.length}. Re-run npm run build:site-facts after the site changes.\n\n` +
    `export const SITE_PAGES = ${JSON.stringify(body)};\n`,
);
console.log(`${pages.length} pages, ${body.length} chars`);
for (const p of pages) console.log(`  ${p.path}  ${p.text.length}`);
